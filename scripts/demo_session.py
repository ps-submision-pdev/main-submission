"""Play the demo conversation with the real model and save the transcript (generated, never edited by hand).

Run from the repo root:  python3 scripts/demo_session.py
Writes data/demo/session_chem_data_s4.md. Uses its own profile file (data/profile/chem_data_s4.demo.json,
reset at the start) so the student's own profile is never touched. Loads .env inside this process only.

Steps: a. intake message; b. the basic Python check questions, answered correctly from the check file
(skipped, and said so, if the questions are not written yet); c. /plan; d. a change request; e. a course
question; f. a new session on the saved profile. Every turn is marked "code", "model" or "fallback",
with the tokens of each model call.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402

from buddy.chat.cli import Session  # noqa: E402
from buddy.llm import LLMClient  # noqa: E402

PERSONA = "chem_data_s4"
PROFILE = ROOT / "data/profile" / f"{PERSONA}.demo.json"
OUT = ROOT / "data/demo" / f"session_{PERSONA}.md"


def block(text: str) -> list[str]:
    return ["```", text, "```", ""]


def main() -> int:
    load_dotenv(ROOT / ".env")
    PROFILE.unlink(missing_ok=True)
    llm = LLMClient(timeout=120)
    lines = [f"# Demo session: {PERSONA} (generated by scripts/demo_session.py)", "",
             f"Model: {llm.model or '(not set)'}. Each turn says who answered it: code (no model call, 0 tokens), "
             "model, or fallback (a model call failed and code answered). Model reasons are guesses, unverified.", ""]
    session = Session(PERSONA, llm, profile_path=PROFILE)
    lines += ["## Session 1", "", "**buddy (start):**", ""] + block(session.start())

    def play(label: str, message: str) -> None:
        turn = session.handle(message)
        lines.extend([f"### {label}", "", f"**student:** {message}", "",
                      f"**answered by:** {turn['by']} | tokens this turn: {turn['tokens']['total_tokens']}", ""])
        for c in turn["calls"]:
            lines.append(f"- call `{c['step']}` ({c['prompt_version']}): ok={c['ok']}, cached={c['cached']}, "
                         f"tokens {c['tokens']['prompt_tokens']} + {c['tokens']['completion_tokens']} = "
                         f"{c['tokens']['total_tokens']}" + (f", error: {c['error']}" if c["error"] else ""))
        lines.extend([""] + block(turn["reply"]))
        print(f"{label}: by={turn['by']} tokens={turn['tokens']['total_tokens']} "
              f"calls={[(c['step'], c['tokens']['total_tokens'], 'ok' if c['ok'] else 'FAILED') for c in turn['calls']]}")

    play("a. intake", "I'm in 2nd year chemical. I want to get into data stuff, but I'm bad at maths. I know some Python.")
    if session.pending:
        answers = " ".join(str(q["answer"] + 1) for q in session.pending["check"]["questions"])
        play("b. check questions (answered correctly from the check file)", answers)
    else:
        lines += ["### b. check questions", "",
                  "Skipped: data/checks/basic_python.json has no written questions yet, so there was nothing to answer "
                  "and basic Python is not skipped.", ""]
        print("b: skipped (check questions not written yet)")
    play("c. /plan", "/plan")
    play("d. change request", "Can I also take Numerical Methods this semester?")
    play("e. course question", "What is Process Dynamics about?")

    first = session
    session = Session(PERSONA, llm, profile_path=PROFILE)
    lines += ["## Session 2 (f. a new session on the saved profile)", "", "**buddy (start):**", ""] + block(session.start())
    print("f: new session greeting shown")

    total = sum(c["tokens"]["total_tokens"] for c in first.calls)
    by = {k: sum(1 for t in first.transcript if t["by"] == k) for k in ("code", "model", "fallback")}
    fell_back = [f"{t['message'][:40]!r}: {c['step']} ({c['error']})" for t in first.transcript for c in t["calls"] if not c["ok"]]
    lines += ["## Totals (session 1)", "", f"- model calls: {len(first.calls)}, tokens: {total}",
              f"- turns answered by code: {by['code']}, by the model: {by['model']}, by a fallback: {by['fallback']}",
              "- fell back: " + ("; ".join(fell_back) if fell_back else "none"), ""]
    print(f"totals: {len(first.calls)} calls, {total} tokens, turns {by}, fallbacks: {fell_back or 'none'}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
