"""Review report: reports/kb_review_<persona_id>.md, generated from the slice and the run's decisions.
Per course it shows the source (database or model), the trust and what the model decided and why, so the
student can check every record against the PDF. No timestamps: the same run gives the same file.
write_decisions() writes the decision log (data/demo/<persona_id>.decisions.jsonl).
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path


def cell(value) -> str:
    """A table cell: no line breaks, and | written as \\| so it does not split the column."""
    return "-" if value in (None, "") else str(value).replace("\n", " / ").replace("|", "\\|")


def table(header: list, rows: list) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join(cell(v) for v in row) + " |" for row in rows] + [""]


def calls(extra: dict) -> list:
    rows = []
    for step, part in (("rank", extra["rank"]), ("prerequisites", extra["prerequisites"]),
                       ("foundations", extra["foundations"])):
        u = part["usage"]
        made = bool(part["decisions"]) and not any(d["verdict"] == "skipped" for d in part["decisions"])
        how = "no call" if not made and u["attempts"] == 0 else "cache hit" if u["attempts"] == 0 else "model call"
        rows.append([step, how, u["attempts"], u["prompt_tokens"], u["completion_tokens"], u["total_tokens"]])
    return rows


def decision_text(record: dict, decision: dict | None) -> str:
    rank = record["rank"]
    if rank is None:
        return "core: not ranked (compulsory)"
    text = (f"#{rank['rank']} in {record['slot']} by {rank['source']}; reason ({rank['reason_source']}, "
            f"trust {rank['trust']}, basis {rank['basis']}): {rank['reason'] or '(dropped)'}")
    if rank.get("reason_check"):
        text += f" [{rank['reason_check']}]"
    if decision and decision.get("mismatch"):
        text += f" [mismatch: {decision['mismatch']}]"
    return text


def write_review(path, kb: dict, extra: dict, db: dict) -> None:
    rank_decisions = {d["said"].get("code"): d for d in extra["rank"]["decisions"] if isinstance(d["said"], dict)}
    out = [f"# KB review: {kb['persona_id']}", "",
           "Generated by buddy.kb_build. Everything below is verified=false until you check it against the PDF.",
           "Model statements are llm_inferred (trust 0.3) and are not facts.", "",
           f"Model: {cell(kb['model'])} | prompts: {kb['prompt_versions']} | rank_source: {kb['rank_source']}",
           f"Horizon (full records): semesters {kb['horizon']} | window {kb['window']} | input hash {kb['input_hash'][:16]}", ""]
    out += ["## Run", ""] + table(["step", "how", "attempts", "prompt tokens", "completion tokens", "total"], calls(extra))
    out += ["## Checks", ""]
    out += [f"- {name}: {'; '.join(found) if found else 'passed'}" for name, found in kb["checks"].items()] + [""]

    rows = []
    for code, r in kb["courses"].items():
        prereqs = ", ".join(f"{e['code']} ({e['source']})" for e in r["prerequisites"]) or r["prerequisite_status"]
        rows.append([code, r["title"], f"{r['l']}-{r['t']}-{r['p']}-{r['credits']}",
                     f"{r['category']} S{r['semester']}" + (f" {r['slot']}" if r["slot"] else ""),
                     f"{r['source']} ({r['provenance']['source_id']} p{r['provenance']['page']})", r["trust"],
                     "yes" if r["text_available"] else "no (title only)",
                     decision_text(r, rank_decisions.get(code)), prereqs, ""])
    out += [f"## A. Courses in the slice ({len(kb['courses'])} full records)", ""]
    out += table(["code", "title", "L-T-P-C", "in slice as", "source", "trust", "text", "model decision and why",
                  "prerequisites", "Your verdict"], rows)

    not_kept = [d for d in extra["rank"]["decisions"] if d["verdict"] != "accepted"]
    out += [f"## Ranked by the model but not kept ({len(not_kept)})", ""]
    out += table(["code", "verdict", "model reason"], [[d["said"].get("code") if isinstance(d["said"], dict) else d["said"],
                                                        d["verdict"], d["said"].get("reason") if isinstance(d["said"], dict) else None]
                                                       for d in not_kept])

    counts = Counter(r["category"] for r in extra["removed"])
    out += [f"## Removed before the model ({len(extra['removed'])}: {dict(sorted(counts.items()))})", ""]
    out += table(["code", "slot", "category", "reason"], [[r["code"], r["slot"], r["category"], r["reason"]]
                                                          for r in extra["removed"]])

    edges = [[c, e["code"], e["source"], e["trust"], e["quote"], e["raw"], e["verified"]]
             for c, r in kb["courses"].items() for e in r["prerequisites"]]
    out += ["## Prerequisites", ""] + table(["course", "prerequisite", "source", "trust", "quote", "raw text", "verified"], edges)
    dropped = [d for d in extra["prerequisites"]["decisions"] if not d["verdict"].startswith("accepted")]
    out += [f"Model proposals not kept ({len(dropped)}):", ""]
    out += table(["proposal", "verdict"], [[d["said"], d["verdict"]] for d in dropped])

    out += ["## Foundations for weaknesses (llm_inferred)", ""]
    out += table(["weakness", "code", "title", "slot", "semester", "reason", "trust"],
                 [[f["weakness"], f["code"], db[f["code"]]["title"]["value"], f["slot"], f["semester"], f["reason"], f["trust"]]
                  for f in kb["foundations"]])
    out += table(["model pick", "verdict"], [[d["said"], d["verdict"]] for d in extra["foundations"]["decisions"]
                                             if d["verdict"] != "accepted"])

    out += ["## Rules", ""]
    out += table(["id", "kind", "clause", "page", "parameters", "source"],
                 [[r["id"], r["kind"], r["provenance"]["clause"], r["provenance"]["page"], r["parameters"],
                   r["provenance"]["url"]] for r in kb["rules"]])
    out += [f"- open limit: {o['text']}" for o in kb["open_limits"]] + [""]

    out += ["## Later slots (codes only, no full records)", ""]
    out += table(["slot", "semester", "options"], [[s["slot"], s["semester"], ", ".join(s["options"])]
                                                   for s in kb["slots"] if not s["full_records"]])
    out += table(["unplaced IDE (no slot number)", "owner"], [[u["code"], u["owner"]] for u in extra["unplaced"]])
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(out), encoding="utf-8")


def write_decisions(path, extra: dict) -> None:
    """The decision log: one JSON line per model decision, accepted or not, in step order.
    Each line: step, said (the model's item as given), verdict (code's verdict), evidence, tokens (of that call)."""
    lines = [json.dumps(d, ensure_ascii=False, sort_keys=True)
             for step in ("rank", "prerequisites", "foundations") for d in extra[step]["decisions"]]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")
